-- Automatic updated_at trigger helper
CREATE OR REPLACE FUNCTION fn_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 1. admins
CREATE TABLE IF NOT EXISTS admins (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    phone      VARCHAR(20)  DEFAULT NULL,
    chat_id    BIGINT       DEFAULT NULL,
    is_active  SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_admins_phone ON admins (phone);
CREATE INDEX IF NOT EXISTS idx_admins_chat_id ON admins (chat_id);

-- 2. supporters
CREATE TABLE IF NOT EXISTS supporters (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    grade      SMALLINT     DEFAULT NULL,
    field      VARCHAR(50)  DEFAULT NULL,
    phone      VARCHAR(20)  DEFAULT NULL,
    chat_id    BIGINT       DEFAULT NULL,
    avatar     VARCHAR(500) DEFAULT NULL,
    is_active  SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_supporters_phone ON supporters (phone);
CREATE INDEX IF NOT EXISTS idx_supporters_field_grade ON supporters (field, grade);
CREATE INDEX IF NOT EXISTS idx_supporters_active ON supporters (is_active);

-- 3. supporter_scopes
CREATE TABLE IF NOT EXISTS supporter_scopes (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supporter_id BIGINT      NOT NULL REFERENCES supporters(id) ON DELETE CASCADE,
    field        VARCHAR(50) NOT NULL,
    grade        SMALLINT    NOT NULL,
    created_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_supporter_scope UNIQUE (supporter_id, field, grade)
);

CREATE INDEX IF NOT EXISTS idx_supporter_scopes_match ON supporter_scopes (field, grade);

-- 4. instructors
CREATE TABLE IF NOT EXISTS instructors (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255) NOT NULL,
    title          VARCHAR(255) DEFAULT NULL,
    description    TEXT         DEFAULT NULL,
    image_url      VARCHAR(500) DEFAULT NULL,
    initial_letter VARCHAR(10)  DEFAULT NULL,
    display_order  INT          NOT NULL DEFAULT 0,
    is_active      SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_instructors_order ON instructors (display_order ASC, id ASC);

-- 5. instructor_social_links
CREATE TABLE IF NOT EXISTS instructor_social_links (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instructor_id BIGINT       NOT NULL REFERENCES instructors(id) ON DELETE CASCADE,
    platform      VARCHAR(50)  NOT NULL,
    url           VARCHAR(500) NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_instructor_social_instructor ON instructor_social_links (instructor_id);

-- 6. students
CREATE TABLE IF NOT EXISTS students (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    national_id  VARCHAR(20)  DEFAULT NULL,
    grade        SMALLINT     DEFAULT NULL,
    field        VARCHAR(50)  DEFAULT NULL,
    phone        VARCHAR(20)  DEFAULT NULL,
    chat_id      BIGINT       DEFAULT NULL,
    supporter_id BIGINT       DEFAULT NULL REFERENCES supporters(id) ON DELETE SET NULL,
    is_active    SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_students_phone ON students (phone);
CREATE INDEX IF NOT EXISTS idx_students_national_id ON students (national_id);
CREATE INDEX IF NOT EXISTS idx_students_supporter ON students (supporter_id);
CREATE INDEX IF NOT EXISTS idx_students_active_field_grade ON students (is_active, field, grade);

-- 7. users
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL UNIQUE,
    phone         VARCHAR(20)  DEFAULT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name     VARCHAR(255) DEFAULT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('admin', 'supporter', 'student', 'teacher')),
    linked_id     BIGINT       DEFAULT NULL,
    chat_id       BIGINT       DEFAULT NULL,
    is_active     SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    last_login    TIMESTAMP    DEFAULT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_users_phone ON users (phone);
CREATE INDEX IF NOT EXISTS idx_users_role_linked ON users (role, linked_id);
CREATE INDEX IF NOT EXISTS idx_users_chat_id ON users (chat_id);

-- 8. parent_contacts
CREATE TABLE IF NOT EXISTS parent_contacts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id   BIGINT       NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    parent_name  VARCHAR(120) NOT NULL,
    relationship VARCHAR(40)  NOT NULL,
    phone        VARCHAR(20)  NOT NULL,
    is_primary   SMALLINT     NOT NULL DEFAULT 0 CHECK (is_primary IN (0, 1)),
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_parent_contacts_student_primary ON parent_contacts (student_id, is_primary DESC, id ASC);
CREATE INDEX IF NOT EXISTS idx_parent_contacts_phone ON parent_contacts (phone);

-- 9. student_supporter_assignments
CREATE TABLE IF NOT EXISTS student_supporter_assignments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id     BIGINT       NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    supporter_id   BIGINT       NOT NULL REFERENCES supporters(id) ON DELETE CASCADE,
    is_active      SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    assigned_by    BIGINT       DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
    note           VARCHAR(255) DEFAULT NULL,
    assigned_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deactivated_at TIMESTAMP    DEFAULT NULL
);

-- PostgreSQL partial unique index: at most one active assignment per student
CREATE UNIQUE INDEX IF NOT EXISTS uk_active_student
    ON student_supporter_assignments (student_id)
    WHERE is_active = 1;

CREATE INDEX IF NOT EXISTS idx_ssa_supporter_active ON student_supporter_assignments (supporter_id, is_active);
CREATE INDEX IF NOT EXISTS idx_ssa_student_history ON student_supporter_assignments (student_id, assigned_at DESC);

-- 10. Authentication & Rate-Limiting Tables
CREATE TABLE IF NOT EXISTS login_codes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    code       VARCHAR(10) NOT NULL,
    used       SMALLINT    NOT NULL DEFAULT 0 CHECK (used IN (0, 1)),
    expires_at TIMESTAMP   NOT NULL,
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_login_codes_lookup ON login_codes (user_id, code, used);

CREATE TABLE IF NOT EXISTS telegram_auth_nonces (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        VARCHAR(20) NOT NULL CHECK (kind IN ('payload', 'ticket')),
    nonce       VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMP   NOT NULL,
    consumed_at TIMESTAMP   DEFAULT NULL,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_tg_nonce UNIQUE (kind, nonce)
);

CREATE INDEX IF NOT EXISTS idx_tg_nonce_expires ON telegram_auth_nonces (expires_at);

CREATE TABLE IF NOT EXISTS telegram_2fa_challenges (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_nonce VARCHAR(64) NOT NULL UNIQUE,
    ticket_jti      VARCHAR(64) NOT NULL,
    user_id         BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    attempts        INT         NOT NULL DEFAULT 0,
    expires_at      TIMESTAMP   NOT NULL,
    consumed_at     TIMESTAMP   DEFAULT NULL,
    created_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_tg_2fa_user ON telegram_2fa_challenges (user_id, expires_at);

CREATE TABLE IF NOT EXISTS auth_throttle (
    throttle_key      VARCHAR(191) PRIMARY KEY,
    attempts          INT          NOT NULL DEFAULT 0,
    window_started_at TIMESTAMP    NOT NULL,
    locked_until      TIMESTAMP    DEFAULT NULL,
    updated_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_auth_throttle_locked ON auth_throttle (locked_until);
