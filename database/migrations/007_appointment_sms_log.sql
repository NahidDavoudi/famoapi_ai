CREATE TABLE IF NOT EXISTS appointment_sms_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id     BIGINT      NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    week_date      DATE        NOT NULL,
    mobile         VARCHAR(20) NOT NULL DEFAULT '',
    recipient_type VARCHAR(20) NOT NULL DEFAULT 'parent'
                   CHECK (recipient_type IN ('student', 'parent')),
    appointment_at TIMESTAMP   DEFAULT NULL,
    status         VARCHAR(30) NOT NULL
                   CHECK (status IN ('sent', 'failed', 'skipped_no_phone')),
    error          TEXT        DEFAULT NULL,
    attempts       INT         NOT NULL DEFAULT 1,
    sent_at        TIMESTAMP   DEFAULT NULL,
    created_by     BIGINT      DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_appointment_sms_log_student_week_mobile UNIQUE (student_id, week_date, mobile)
);

CREATE INDEX IF NOT EXISTS idx_appointment_sms_log_week_status
    ON appointment_sms_log (week_date, status);

CREATE INDEX IF NOT EXISTS idx_appointment_sms_log_student_week
    ON appointment_sms_log (student_id, week_date);

DROP TRIGGER IF EXISTS trg_appointment_sms_log_updated_at ON appointment_sms_log;
CREATE TRIGGER trg_appointment_sms_log_updated_at
BEFORE UPDATE ON appointment_sms_log
FOR EACH ROW
EXECUTE FUNCTION fn_set_updated_at();
