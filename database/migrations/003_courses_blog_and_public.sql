-- 1. courses
CREATE TABLE IF NOT EXISTS courses (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(255) NOT NULL,
    icon                 VARCHAR(100) DEFAULT NULL,
    gradient_color_from  VARCHAR(50)  DEFAULT NULL,
    gradient_color_to    VARCHAR(50)  DEFAULT NULL,
    background_image_url VARCHAR(500) DEFAULT NULL,
    description          TEXT         DEFAULT NULL,
    price                BIGINT       NOT NULL DEFAULT 0,
    display_order        INT          NOT NULL DEFAULT 0,
    is_active            SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_courses_order ON courses (display_order ASC, id ASC);

-- 2. course_features
CREATE TABLE IF NOT EXISTS course_features (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id     BIGINT       NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    feature_text  VARCHAR(500) NOT NULL,
    display_order INT          NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_course_features_course ON course_features (course_id, display_order ASC);

-- 3. subscriptions (normalized with BIGINT FKs to courses.id and students.id)
CREATE TABLE IF NOT EXISTS subscriptions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id  BIGINT      NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    student_id BIGINT      NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    status     VARCHAR(30) NOT NULL DEFAULT 'pending',
    is_active  SMALLINT    NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    note       TEXT        DEFAULT NULL,
    started_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    end_at     TIMESTAMP   DEFAULT NULL,
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_subscriptions_student ON subscriptions (student_id, is_active);
CREATE INDEX IF NOT EXISTS idx_subscriptions_course ON subscriptions (course_id);

-- 4. blog_category
CREATE TABLE IF NOT EXISTS blog_category (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    slug        VARCHAR(255) NOT NULL UNIQUE,
    icon        VARCHAR(100) DEFAULT 'fa-folder',
    color       VARCHAR(50)  DEFAULT '#6366f1',
    description TEXT         DEFAULT NULL,
    sort_order  INT          NOT NULL DEFAULT 0,
    is_active   SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_blog_category_sort ON blog_category (is_active, sort_order ASC, name ASC);

-- 5. blog_posts
CREATE TABLE IF NOT EXISTS blog_posts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(255) NOT NULL,
    slug             VARCHAR(255) NOT NULL UNIQUE,
    excerpt          TEXT         DEFAULT NULL,
    content          TEXT         NOT NULL,
    cover_image      VARCHAR(500) DEFAULT NULL,
    category_id      BIGINT       DEFAULT NULL REFERENCES blog_category(id) ON DELETE SET NULL,
    meta_description VARCHAR(500) DEFAULT NULL,
    is_published     SMALLINT     NOT NULL DEFAULT 0 CHECK (is_published IN (0, 1)),
    published_at     TIMESTAMP    DEFAULT NULL,
    views            INT          NOT NULL DEFAULT 0,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_blog_posts_published ON blog_posts (is_published, published_at DESC);
CREATE INDEX IF NOT EXISTS idx_blog_posts_category ON blog_posts (category_id, is_published);
