-- 1. daily_attendance
CREATE TABLE IF NOT EXISTS daily_attendance (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attendance_date DATE         NOT NULL,
    student_id      BIGINT       DEFAULT NULL REFERENCES students(id) ON DELETE CASCADE,
    guest_name      VARCHAR(255) DEFAULT NULL,
    field           VARCHAR(50)  DEFAULT NULL,
    status          VARCHAR(20)  NOT NULL DEFAULT 'present' CHECK (status IN ('present', 'absent', 'excused')),
    arrived_at      TIMESTAMP    DEFAULT NULL,
    exam_started_at TIMESTAMP    DEFAULT NULL,
    exam_ended_at   TIMESTAMP    DEFAULT NULL,
    departed_at     TIMESTAMP    DEFAULT NULL,
    removed_at      TIMESTAMP    DEFAULT NULL,
    removed_by      BIGINT       DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_by      BIGINT       DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
    client_uuid     VARCHAR(36)  DEFAULT NULL UNIQUE,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_att_date_student UNIQUE (attendance_date, student_id)
);

CREATE INDEX IF NOT EXISTS idx_att_date_field ON daily_attendance (attendance_date, field);
CREATE INDEX IF NOT EXISTS idx_att_student_date ON daily_attendance (student_id, attendance_date);

-- 2. tutoring_classrooms
CREATE TABLE IF NOT EXISTS tutoring_classrooms (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    instructor_id BIGINT       NOT NULL UNIQUE REFERENCES instructors(id) ON DELETE CASCADE,
    sort_order    INT          NOT NULL DEFAULT 0,
    is_active     SMALLINT     NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 3. tutoring_sessions
CREATE TABLE IF NOT EXISTS tutoring_sessions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_date      DATE        NOT NULL,
    classroom_id      BIGINT      NOT NULL REFERENCES tutoring_classrooms(id) ON DELETE CASCADE,
    student_id        BIGINT      NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    attendance_id     BIGINT      DEFAULT NULL REFERENCES daily_attendance(id) ON DELETE SET NULL,
    entered_at        TIMESTAMP   NOT NULL,
    ended_at          TIMESTAMP   DEFAULT NULL,
    client_entered_at TIMESTAMP   DEFAULT NULL,
    entry_source      VARCHAR(20) NOT NULL DEFAULT 'auto' CHECK (entry_source IN ('auto', 'manual', 'backfill')),
    needs_review      SMALLINT    NOT NULL DEFAULT 0 CHECK (needs_review IN (0, 1)),
    created_by        BIGINT      DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
    client_uuid       VARCHAR(36) DEFAULT NULL UNIQUE,
    created_at        TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- PostgreSQL partial unique index: at most one open session per student
CREATE UNIQUE INDEX IF NOT EXISTS uq_sess_one_open_per_student
    ON tutoring_sessions (student_id)
    WHERE ended_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_sess_classroom_open ON tutoring_sessions (classroom_id, ended_at);
CREATE INDEX IF NOT EXISTS idx_sess_student_date ON tutoring_sessions (student_id, session_date);
CREATE INDEX IF NOT EXISTS idx_sess_date_classroom ON tutoring_sessions (session_date, classroom_id);

