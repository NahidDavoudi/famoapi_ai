-- 1. exam_comments
CREATE TABLE IF NOT EXISTS exam_comments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      BIGINT    NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    exam_date       DATE      NOT NULL,
    teacher_user_id BIGINT    NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    body            TEXT      NOT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_exam_comments_student_date_teacher UNIQUE (student_id, exam_date, teacher_user_id)
);

CREATE INDEX IF NOT EXISTS idx_exam_comments_student_date ON exam_comments (student_id, exam_date);

DROP TRIGGER IF EXISTS trg_exam_comments_updated_at ON exam_comments;
CREATE TRIGGER trg_exam_comments_updated_at
BEFORE UPDATE ON exam_comments
FOR EACH ROW
EXECUTE FUNCTION fn_set_updated_at();

-- 2. exam_result_links
CREATE TABLE IF NOT EXISTS exam_result_links (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash     CHAR(64)  NOT NULL UNIQUE,
    student_id     BIGINT    NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    exam_date      DATE      NOT NULL,
    expires_at     TIMESTAMP NOT NULL,
    revoked_at     TIMESTAMP DEFAULT NULL,
    sms_sent_at    TIMESTAMP DEFAULT NULL,
    created_by     BIGINT    DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
    last_viewed_at TIMESTAMP DEFAULT NULL,
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_exam_result_links_student_date ON exam_result_links (student_id, exam_date);
CREATE INDEX IF NOT EXISTS idx_exam_result_links_expires ON exam_result_links (expires_at);
