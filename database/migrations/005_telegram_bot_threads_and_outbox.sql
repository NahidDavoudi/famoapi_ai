CREATE INDEX IF NOT EXISTS idx_reports_status_date ON reports_status (report_date DESC);
CREATE INDEX IF NOT EXISTS idx_reports_status_supporter ON reports_status (supporter_id, status);

CREATE OR REPLACE FUNCTION fn_calc_report_response_time()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.status = 1 AND (OLD.status IS NULL OR OLD.status = 0) THEN
        IF NEW.replied_at IS NULL THEN
            NEW.replied_at = CURRENT_TIMESTAMP;
        END IF;
        NEW.response_time_seconds = GREATEST(
            0,
            EXTRACT(EPOCH FROM (NEW.replied_at - OLD.report_date))::INT
        );
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_reports_status_response_time ON reports_status;
CREATE TRIGGER trg_reports_status_response_time
BEFORE UPDATE ON reports_status
FOR EACH ROW
EXECUTE FUNCTION fn_calc_report_response_time();
