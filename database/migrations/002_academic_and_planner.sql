-- 1. files
CREATE TABLE IF NOT EXISTS files (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_type  VARCHAR(30)  NOT NULL DEFAULT 'student',
    owner_id    BIGINT       NOT NULL,
    file_type   VARCHAR(50)  DEFAULT NULL,
    report_date DATE         DEFAULT NULL,
    file_path   VARCHAR(500) NOT NULL,
    file_size   BIGINT       DEFAULT NULL,
    description TEXT         DEFAULT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_files_owner ON files (owner_type, owner_id);
CREATE INDEX IF NOT EXISTS idx_files_report_date ON files (report_date);

-- 2. exam_results
CREATE TABLE IF NOT EXISTS exam_results (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT        NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    file_id    BIGINT        DEFAULT NULL REFERENCES files(id) ON DELETE SET NULL,
    exam_date  DATE          NOT NULL,
    subject    VARCHAR(100)  NOT NULL,
    chapter    VARCHAR(255)  DEFAULT NULL,
    total_q    INT           NOT NULL DEFAULT 0,
    correct    INT           NOT NULL DEFAULT 0,
    wrong      INT           NOT NULL DEFAULT 0,
    skipped    INT           NOT NULL DEFAULT 0,
    percentage NUMERIC(5, 2) GENERATED ALWAYS AS (
        CASE
            WHEN total_q > 0 THEN ROUND(((correct * 3.0 - wrong) / (total_q * 3.0)) * 100.0, 2)
            ELSE 0
        END
    ) STORED,
    created_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_exam_results_student_date ON exam_results (student_id, exam_date DESC);

-- 3. topic_tree
CREATE TABLE IF NOT EXISTS topic_tree (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id    BIGINT       DEFAULT NULL REFERENCES topic_tree(id) ON DELETE CASCADE,
    label        VARCHAR(255) NOT NULL,
    grade        SMALLINT     DEFAULT NULL,
    field        VARCHAR(50)  DEFAULT NULL,
    subject_name VARCHAR(100) DEFAULT NULL,
    sort_order   INT          NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_topic_tree_parent ON topic_tree (parent_id, sort_order ASC, id ASC);
CREATE INDEX IF NOT EXISTS idx_topic_tree_filter ON topic_tree (grade, field);

-- 4. weekly_plans
CREATE TABLE IF NOT EXISTS weekly_plans (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id   BIGINT      NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    week_date    VARCHAR(20) NOT NULL,
    weekly_notes TEXT        DEFAULT NULL,
    times_json   TEXT        DEFAULT NULL,
    created_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_weekly_plan_student_week UNIQUE (student_id, week_date)
);

CREATE INDEX IF NOT EXISTS idx_weekly_plans_student ON weekly_plans (student_id, id DESC);

-- 5. events
CREATE TABLE IF NOT EXISTS events (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id          BIGINT       NOT NULL REFERENCES weekly_plans(id) ON DELETE CASCADE,
    student_id       BIGINT       NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    day_index        SMALLINT     NOT NULL DEFAULT 0,
    day_name         VARCHAR(30)  DEFAULT NULL,
    time_index       SMALLINT     NOT NULL DEFAULT 0,
    time_label       VARCHAR(50)  DEFAULT NULL,
    topic_id         VARCHAR(30)  DEFAULT NULL,
    topic_path       TEXT         DEFAULT NULL,
    topic_path_short VARCHAR(255) DEFAULT NULL,
    topic_label      VARCHAR(200) DEFAULT NULL,
    subject_name     VARCHAR(100) DEFAULT NULL,
    selected_grade   SMALLINT     DEFAULT NULL,
    title            VARCHAR(255) DEFAULT NULL,
    notes            TEXT         DEFAULT NULL,
    color            VARCHAR(30)  DEFAULT 'green',
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_events_plan ON events (plan_id, day_index ASC, time_index ASC);
CREATE INDEX IF NOT EXISTS idx_events_student ON events (student_id);

-- 6. event_topics
